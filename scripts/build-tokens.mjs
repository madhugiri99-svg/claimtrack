// Generates src/tokens/tokens.css from src/tokens/tokens.json.
// Variable names match the code syntax set on each Figma variable,
// e.g. Figma "color/action/primary" -> CSS var(--color-action-primary).
import { readFileSync, writeFileSync } from 'node:fs';

const src = new URL('../src/tokens/tokens.json', import.meta.url);
const out = new URL('../src/tokens/tokens.css', import.meta.url);
const tokens = JSON.parse(readFileSync(src, 'utf8'));

const cssName = (name) => `--${name.replaceAll('/', '-')}`;
const resolve = (value) => {
  const alias = /^\{(.+)\}$/.exec(value);
  if (!alias) return value;
  if (!(alias[1] in tokens.primitives)) throw new Error(`Unknown primitive: ${alias[1]}`);
  return `var(${cssName(alias[1])})`;
};

const lines = [];
const section = (title) => lines.push('', `  /* ${title} */`);

section('Primitives — use semantic tokens in components, not these');
for (const [name, value] of Object.entries(tokens.primitives))
  lines.push(`  ${cssName(name)}: ${value};`);

section('Semantic colors');
for (const [name, value] of Object.entries(tokens.color))
  lines.push(`  ${cssName(name)}: ${resolve(value)};`);

section('Spacing');
for (const [name, value] of Object.entries(tokens.spacing))
  lines.push(`  ${cssName(name)}: ${value}px;`);

section('Radius');
for (const [name, value] of Object.entries(tokens.radius))
  lines.push(`  ${cssName(name)}: ${value}px;`);

section('Typography');
for (const [name, value] of Object.entries(tokens.typography)) {
  if (name.startsWith('$')) continue;
  if (typeof value === 'string') {
    lines.push(`  ${cssName(name)}: ${value};`);
    continue;
  }
  const [weight, size, lineHeight] = value;
  const base = cssName(name);
  lines.push(
    `  ${base}-weight: ${weight};`,
    `  ${base}-size: ${size / 16}rem;`,
    `  ${base}-line-height: ${lineHeight / size};`,
  );
}

const css = `/* Generated by scripts/build-tokens.mjs from tokens.json. Do not edit by hand. */\n:root {${lines.join('\n')}\n}\n`;
writeFileSync(out, css);
console.log(`Wrote ${out.pathname}`);
